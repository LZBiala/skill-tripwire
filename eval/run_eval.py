"""Score the scanner against the corpus and emit REPORT.md, deterministically.

The number this project lives or dies on is not the detection rate. It is the pairing of
detection rate WITH false-positive rate, per rule, with denominators, a rule-of-three bound
where a count is zero, and precision recomputed at the ~2% base rate the field actually
measures - because at a low base rate the false-positive rate, not recall, decides whether an
alarm is believable. The held-out arm is reported separately, and its numbers are the honest
ones: the rules were never tuned on it.

Run `python eval/run_eval.py` to print the report; `--write` saves it. CI runs it without
`--write` and fails if the committed REPORT.md drifts, the same drift gate the whole portfolio
carries.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "corpus"))

import samples  # noqa: E402
from skill_tripwire.rules import RULE_REGISTRY  # noqa: E402
from skill_tripwire.scan import scan  # noqa: E402

BASE_RATE = 0.02  # Snyk ToxicSkills measured ~2% of a public marketplace as truly malicious


def _flagged(text: str) -> tuple[bool, set[str]]:
    r = scan(text)
    return (r.verdict != "PASS", {f.rule_id for f in r.findings})


def _pct(n: int, d: int) -> str:
    return f"{100.0 * n / d:.1f}%" if d else "n/a"


def _rule_of_three(d: int) -> str:
    # With zero events in d trials, the 95% upper bound on the rate is about 3/d.
    return f"<= {100.0 * 3 / d:.1f}%" if d else "n/a"


def _arm(rows: list[dict]) -> dict:
    mal = [s for s in rows if s["malicious"]]
    ben = [s for s in rows if not s["malicious"]]
    caught = [s for s in mal if _flagged(s["text"])[0]]
    fps = [s for s in ben if _flagged(s["text"])[0]]
    return {
        "n_mal": len(mal), "n_ben": len(ben),
        "caught": len(caught), "missed": [s["id"] for s in mal if s not in caught],
        "fp": len(fps), "fp_ids": [s["id"] for s in fps],
    }


def _bayes_precision(recall: float, fpr_for_calc: float) -> str:
    denom = recall * BASE_RATE + fpr_for_calc * (1 - BASE_RATE)
    return f"{100.0 * (recall * BASE_RATE) / denom:.1f}%" if denom else "n/a"


def build_report() -> str:
    rows = samples.build()
    tuned = [s for s in rows if not s["held_out"]]
    held = [s for s in rows if s["held_out"]]

    L: list[str] = []
    L.append("# skill-tripwire evaluation report")
    L.append("")
    L.append("Regenerated by `python eval/run_eval.py`. CI fails the build if this file drifts")
    L.append("from what the code produces, so every number here is reproducible from a clone.")
    L.append("")
    L.append("A detection rate alone is not published anywhere in this file. Each rate carries")
    L.append("its denominator, a rule-of-three bound where a count is zero, and - for the")
    L.append(f"headline - precision recomputed at the ~{int(BASE_RATE*100)}% base rate the field measures.")
    L.append("")

    # ---- detection: an honest label for a self-authored corpus ----
    # The samples here were written by the same person who wrote the rules. That makes NONE of
    # these a generalization measurement: the author chose the sample counts and pre-decided
    # which would be caught and which would be missed. Calling any ratio here "generalization"
    # would re-commit the self-authored-catalogue mistake this project cites as its founding
    # lesson. So the numbers below are labeled for exactly what they are, and the one number
    # that would be a real measurement - performance on an externally-authored set - is named
    # as the top open item, not faked with a home-made proxy.
    ta, ha = _arm(tuned), _arm(held)
    t_recall = ta["caught"] / ta["n_mal"] if ta["n_mal"] else 0.0
    h_recall = ha["caught"] / ha["n_mal"] if ha["n_mal"] else 0.0
    L.append("## Detection on the self-authored corpus (NOT a generalization number)")
    L.append("")
    L.append(f"- on samples the rules were built against: "
             f"{ta['caught']}/{ta['n_mal']} = {_pct(ta['caught'], ta['n_mal'])}. This is an "
             "upper bound and nothing more.")
    L.append(f"- on the author's own limit-probe set (written knowing the rules, each sample "
             f"pre-labeled a designed catch or a designed miss): "
             f"{ha['caught']}/{ha['n_mal']} = {_pct(ha['caught'], ha['n_mal'])}.")
    if ha["missed"]:
        L.append(f"- probes that miss, kept on the scorecard (each a real, named limit): "
                 f"{', '.join(ha['missed'])}")
    L.append("")
    L.append("Read that second line as a demonstration, not a measurement. The catches show the")
    L.append("canonicalize-and-decode pipeline defeats obfuscation; the misses document limits")
    L.append("the deterministic rules genuinely cannot reach (homoglyphs, no-token semantics,")
    L.append("cross-line dataflow, capability drift beyond shell). But the author picked the")
    L.append("samples, so the RATIO measures the author's imagination, not the tool's reach.")
    L.append("")
    L.append("**The one number that would be a real measurement - detection on a corpus authored")
    L.append("by someone else (published third-party PoCs, another researcher's samples) - is not")
    L.append("yet computed. It is the top open item, and no home-made proxy is printed in its**")
    L.append("**place.** Substituting a self-authored set for it is the exact error this repo warns about.")
    L.append("")

    # ---- false positives: one number over ALL benign; the tuned/held split is not meaningful
    # for negatives, and a two-sample denominator is not a rate worth printing.
    ben = [s for s in rows if not s["malicious"]]
    ben_fp = [s for s in ben if _flagged(s["text"])[0]]
    n_ben = len(ben)
    fpr = len(ben_fp) / n_ben if n_ben else 0.0
    fpr_calc = fpr if ben_fp else (3 / n_ben if n_ben else 0.0)
    L.append("## False positives (all benign samples, several chosen as probes)")
    L.append("")
    if ben_fp:
        L.append(f"- false positives: {len(ben_fp)}/{n_ben} = {_pct(len(ben_fp), n_ben)} "
                 f"({', '.join(s['id'] for s in ben_fp)})")
    else:
        L.append(f"- false positives: 0/{n_ben}, so FPR {_rule_of_three(n_ben)} (rule of three)")
    L.append(f"- benign probes included: IMPORTANT phrasing, a narrow Bash grant, a matching "
             f"WebFetch grant, a UUID, a credentials path, a benign base64 blob, a curl mention")
    L.append("")

    # ---- precision at the base rate: the number that actually decides adoption ----
    L.append(f"## Precision at the measured ~{int(BASE_RATE*100)}% marketplace base rate")
    L.append("")
    L.append(f"- using the limit-probe recall and the FPR bound: "
             f"{_bayes_precision(h_recall, fpr_calc)}")
    L.append(f"- using the tuned upper-bound recall: "
             f"{_bayes_precision(t_recall, fpr_calc)}")
    L.append("(Both use self-authored recall, so read them as illustrations of the base-rate")
    L.append("effect, not as field precision.)")
    L.append("")
    L.append("Read those twice. Even at the flattering recall, a scanner at a 2% base rate with")
    L.append("a realistic false-positive rate is mostly wrong when it alarms. That is the base-")
    L.append("rate fallacy (Axelsson), and it is why the noisy rules here route to REVIEW and")
    L.append("never hard-block, and why this small curated benign set will read cleaner than the")
    L.append("wild. FPR, not recall, is the number that decides whether anyone trusts the alarm.")
    L.append("")

    # ---- per-rule table ----
    L.append("## Per rule (whole corpus)")
    L.append("")
    L.append("| rule | tier | owasp | recall on its targets | precision when it fires | flagged benign |")
    L.append("|---|---|---|---|---|---:|")
    for rule_id, (tier, owasp) in RULE_REGISTRY.items():
        targets = [s for s in rows if s["expect_rule"] == rule_id]
        hit = sum(1 for s in targets if rule_id in _flagged(s["text"])[1])
        fired = [s for s in rows if rule_id in _flagged(s["text"])[1]]
        fired_mal = sum(1 for s in fired if s["malicious"])
        fired_benign = len(fired) - fired_mal
        rec = f"{hit}/{len(targets)} = {_pct(hit, len(targets))}" if targets else "no targets"
        prec = f"{fired_mal}/{len(fired)} = {_pct(fired_mal, len(fired))}" if fired else "never fired"
        L.append(f"| {rule_id} | {tier} | {owasp} | {rec} | {prec} | {fired_benign} |")
    L.append("")
    L.append("Per-rule precision is 100% on this corpus only because no benign sample triggers")
    L.append("any rule here; on a wild benign set the noisy warn-tier rules would drop it, which")
    L.append("is why they route to REVIEW and never hard-block. The column is reported in full")
    L.append("rather than summarized, because the frozen rubric asked for precision AND recall.")
    L.append("")
    L.append("## The ceiling, stated")
    L.append("")
    L.append("These numbers are a floor measured on a small seeded corpus, not a guarantee.")
    L.append("Independent studies show static scanners lose 45-99% of findings under payload-")
    L.append("preserving obfuscation, and semantic attacks with no trigger token are out of")
    L.append("deterministic reach entirely (see the held-out misses above). skill-tripwire is a")
    L.append("triage layer; containment belongs to sandboxing and architecture.")
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    report = build_report()
    if "--write" in argv:
        out = Path(__file__).resolve().parent / "REPORT.md"
        out.write_text(report, encoding="utf-8")
        sys.stderr.write(f"wrote {out}\n")
    else:
        sys.stdout.write(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
